#!/usr/bin/env python3
"""Generate unitab.h: the Unicode \\p{L} / \\p{N} / \\s range tables that hftok.c's
Qwen2 pretokenizer needs (C has no Unicode character classes of its own).

    pip install regex
    python tools/gen_unitab.py > unitab.h

Classes are taken from the `regex` module (its tables track a recent Unicode
version; Python's own unicodedata is pinned to the interpreter's, 13.0 on 3.9).
Every code point 0..0x10FFFF is probed, so coverage is complete for the Unicode
version `regex` ships -- not a hand-picked script list. Output: sorted, merged
[lo, hi] ranges, searched by binary search at runtime (~5 KB of tables).
"""
import sys

import regex


def ranges(pat):
    rx = regex.compile(pat)
    out, lo, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # surrogates never occur in valid UTF-8
        if rx.match(chr(cp)):
            if lo is None:
                lo = cp
            elif cp != prev + 1:
                out.append((lo, prev))
                lo = cp
            prev = cp
    if lo is not None:
        out.append((lo, prev))
    return out


def emit(name, rs):
    print(f"static const uint32_t {name}[][2] = {{   // {len(rs)} ranges")
    line = "  "
    for lo, hi in rs:
        item = f"{{0x{lo:X},0x{hi:X}}},"
        if len(line) + len(item) > 96:
            print(line.rstrip())
            line = "  "
        line += item
    print(line.rstrip())
    print("};")


def main():
    L = ranges(r"\p{L}")
    N = ranges(r"\p{N}")
    S = ranges(r"\s")
    print("// unitab.h - GENERATED by tools/gen_unitab.py (regex %s) -- do not edit." % regex.__version__)
    print("// Unicode \\p{L} (letters), \\p{N} (numbers) and \\s (White_Space) as sorted,")
    print("// merged inclusive code-point ranges, for hftok.c's Qwen2 pretokenizer.")
    print("#ifndef UNITAB_H")
    print("#define UNITAB_H")
    print("#include <stdint.h>")
    emit("UNI_L", L)
    emit("UNI_N", N)
    emit("UNI_S", S)
    print("#endif // UNITAB_H")
    sys.stderr.write("L=%d N=%d S=%d ranges\n" % (len(L), len(N), len(S)))


if __name__ == "__main__":
    main()
