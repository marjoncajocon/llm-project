func colabHygiene(d *doc) {
	d.h1("Memory and disk discipline")

	d.p("This is the section that exists because a run was killed. Colab gives you room, not " +
		"immunity.")

	d.h2("Every run writes a full checkpoint")
	d.p("There is deliberately no mid-run checkpointing in GRPO: saving would mean merging the " +
		"adapters into the base, and the merge resets B to zero, after which the adapter gradient is " +
		"identically zero and training stalls. A run therefore saves exactly once, at the end - and " +
		"that save is a full 621 MB, not a small adapter file.")
	d.bullet("Delete throwaway checkpoints as soon as you have read the number you wanted from them.")
	d.bullet("Write experimental output to /tmp so a runtime restart clears it automatically.")
	d.bullet("Copy only checkpoints you actually intend to keep back to Drive.")
	d.code(
		"!ls -la --block-size=M model/smollm/*.bin /tmp/*.bin 2>/dev/null",
		"!rm -f /tmp/probe.bin /tmp/eval_*.bin",
		"!df -h /content | tail -1",
		"!free -g | head -2",
	)

	d.h2("Evaluating without training")
	d.p("Passing --lr 0 turns the trainer into a scorer: it still samples the full group per task " +
		"and reports the reward, but no parameter changes. This was verified by hashing - a run at " +
		"--lr 0 writes a checkpoint byte-identical to its input.")
	d.code(
		"# paired evaluation: identical seed and task file, only --model differs",
		"!./build/transformer-linux-x86_64-gpu grpo data/grpo_hard_eval.txt \\",
		"    --model model/smollm/reason_e2.bin --hf-tok model/smollm/tok.hf \\",
		"    --out /tmp/eval_before.bin --steps 20 --lr 0 --seed 7 --verbose",
	)
	d.note("Both task selection and token sampling are seeded from --seed, so the same seed on the " +
		"same task file draws the same tasks in the same order. That is what makes the comparison " +
		"paired rather than two independent samples.")
}

