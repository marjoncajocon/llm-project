func colabSetup(d *doc) {
	d.h1("Setting up the runtime")

	d.h2("Pick the runtime")
	d.p("Runtime, then Change runtime type. A GPU runtime is worth taking even given section 1.3, " +
		"because the update passes do benefit and the GPU runtimes tend to come with more RAM. If " +
		"you have Colab Pro, a high-RAM runtime removes the memory question entirely.")

	d.h2("Get the binary")
	d.p("The repository ships a cross-compiled Linux binary, so nothing has to be built on Colab:")
	d.code(
		"!git clone <your-remote> llm-project",
		"%cd llm-project",
		"!chmod +x build/transformer-linux-x86_64-gpu",
		"!./build/transformer-linux-x86_64-gpu gpu-info",
	)
	d.p("If you build it yourself instead, produce it on your own machine with either of these, and " +
		"upload the result - Colab is not set up to cross-compile this tree:")
	d.code(
		"powershell -File tools\\build_gpu.ps1 -Only colab   # Windows",
		"make cross-gpu                                      # Linux/macOS",
	)

	d.h2("Install the OpenCL loader")
	d.p("Colab ships the NVIDIA driver, which provides OpenCL, but usually not the vendor-neutral " +
		"loader or the ICD registration file that points the loader at NVIDIA. Both are one line. " +
		"Skipping this is survivable - gpu.c falls back to opening libnvidia-opencl.so.1 directly - " +
		"but installing the loader is the supported path.")
	d.code(
		"!apt-get -qq update && apt-get -qq install -y ocl-icd-libopencl1 clinfo > /dev/null",
		"!mkdir -p /etc/OpenCL/vendors && echo libnvidia-opencl.so.1 > /etc/OpenCL/vendors/nvidia.icd",
		"!clinfo -l",
	)

	d.h2("Validate before you train")
	d.p("Run the smoke test first. Part [30] is the one that matters: it runs the forward matmul and " +
		"both backward matmuls on deliberately ragged shapes - not multiples of the kernel's 16-wide " +
		"tile or 64-column block - and requires the GPU to agree with the CPU. It also checks that " +
		"the backward kernels accumulate into pre-seeded gradients instead of overwriting them.")
	d.code("!./build/transformer-linux-x86_64-gpu 2>&1 | tail -n 30")
	d.warn("A fast wrong answer is not a speedup. If part [30] is not green, stop - every number " +
		"produced after that point is meaningless.")
	d.note("tools/colab_gpu_test.ipynb automates this entire section and adds a CPU-versus-GPU " +
		"benchmark. Run it once before the first GRPO job.")
}

