func colabData(d *doc) {
	d.h1("Regenerating the task data")

	d.p("Task files are gitignored, so they are generated on Colab rather than uploaded. This is " +
		"deterministic given --seed, so the file you build there is the file you would have built " +
		"at home.")

	d.h2("The two-step pipeline")
	d.p("Generate, then gate. The gate is not optional: an ungrounded reference would make the " +
		"reward pay out for a hallucination, and reward and truth would come apart.")
	d.code(
		"!python tools/hard_tasks.py --out data/hard_raw.txt --n 600 \\",
		"    --wiki data/wiki --commands data/so_commands.txt --reason",
		"!python tools/grpo_tasks.py --out data/grpo_hard.txt data/hard_raw.txt",
	)
	d.p("Expect all 600 to survive the gate. If a run reports drops, a template in hard_tasks.py has " +
		"produced a reference that is not grounded in its own prompt - fix the template, do not " +
		"loosen the gate.")

	d.h2("Why data/wiki matters more than it looks")
	d.p("slugs_from_wiki falls back to six generic slugs when the directory is missing, and the " +
		"write-content pool is derived from those same slugs. With the fallback, the content " +
		"vocabulary collapses to roughly ten words - small enough for the model to memorize the " +
		"content set instead of learning to copy content out of the prompt. That failure has been " +
		"observed in this project before: novel first-write content copied fine while the second " +
		"write's body was dropped to empty.")
	d.warn("Upload data/wiki. Without it the generator still runs and still passes the gate, but the " +
		"tasks quietly get easier and the flat-group rate climbs back up.")
	d.code(
		"# on your machine: Compress-Archive data/wiki wiki.zip",
		"!unzip -q wiki.zip -d data/",
		"!ls data/wiki | wc -l      # expect 383",
	)

	d.h2("A held-out set for honest evaluation")
	d.p("Use a different generator seed. This gives tasks from the same distribution with zero " +
		"line overlap, which is what makes a before/after comparison meaningful.")
	d.code(
		"!python tools/hard_tasks.py --out data/hard_eval_raw.txt --n 200 \\",
		"    --wiki data/wiki --commands data/so_commands.txt --reason --seed 4242",
		"!python tools/grpo_tasks.py --out data/grpo_hard_eval.txt data/hard_eval_raw.txt",
	)
}

