func colabPromote(d *doc) {
	d.h1("Deciding whether to promote")

	d.p("A finished run is not a better model. The project rule is that nothing is promoted without " +
		"measurement, and the standing risk in this tree has been features built but never validated " +
		"end to end.")

	d.h2("The gate")
	d.code(
		"!python tools/remeasure.py model/smollm/grpo_hard.bin",
		"!python tools/probe3.py    model/smollm/grpo_hard.bin",
	)
	d.p("remeasure.py runs the full set - probe3, sft_memtest and eval_critic - against the recorded " +
		"baseline, and prints a question mark for anything it could not parse, so a missing number " +
		"never reads as a pass. It was built precisely so that a probe cannot be skipped.")
	d.warn("sft_memtest execs the engine argv verbatim, so it needs an ABSOLUTE path to the binary. " +
		"probe3 and eval_critic resolve paths internally and once hid this problem for a whole run.")

	d.h2("What promotion means")
	d.bullet("Copy the checkpoint back to Drive before the runtime disconnects and takes it with it.")
	d.bullet("Record the numbers in notes.md and memory.md, including the ones that did not improve.")
	d.bullet("If nothing improved, that is a result worth committing too - it stops the next session " +
		"from re-running the same experiment.")
}

