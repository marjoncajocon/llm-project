// ===========================================================================
func colabWhy(d *doc) {
	d.h1("Why move GRPO to Colab")

	d.lead("Because GRPO is the one workload here that runs out of memory, and because a killed run " +
		"wastes an hour rather than a minute.")

	d.h2("What actually went wrong locally")
	d.p("A paired before/after evaluation was run on 5 September 2026: two GRPO invocations in " +
		"sequence, each loading a 621 MB checkpoint and each writing another 621 MB checkpoint at " +
		"the end. The first completed. The second was killed by the operating system at step 14 of " +
		"20 with a low-memory condition. Nothing was corrupted and the partial result was still " +
		"usable, but an hour of compute produced three quarters of an answer.")
	d.p("The arithmetic is unforgiving. One resident model is 621 MB. Each finished run writes a " +
		"fresh 621 MB checkpoint to disk. Run three experiments back to back without cleaning up and " +
		"roughly 1.9 GB of dead weight is sitting in the working directory while the next model " +
		"loads on top of it.")

	d.h2("What Colab fixes, and what it does not")
	d.table([]string{"Constraint", "Desktop", "Colab (standard)"}, []float64{54, 60, 60}, [][]string{
		{"System RAM", "shared with everything else", "~12.7 GB dedicated"},
		{"Disk for checkpoints", "your own drive", "~100 GB ephemeral"},
		{"CPU threads", "set TF_THREADS=3 to stay usable", "~2 vCPU on the free tier"},
		{"GPU", "integrated GPU is SLOWER than the CPU", "T4 available, but see 1.3"},
		{"Interruption risk", "killed by memory pressure", "disconnects when idle"},
	})
	d.warn("Colab is a memory fix, not a speed fix. On the free tier you get about two vCPUs, which " +
		"is FEWER than the three threads a local run is limited to. Per-step wall clock can be worse.")

	d.h2("Why the GPU does not rescue the rollout phase")
	d.p("The OpenCL backend offloads a matmul only when the M dimension is large enough to pay for " +
		"the transfer, governed by TF_GPU_MIN_M. Single-token decode has M=1: it is memory-bandwidth " +
		"bound, so it deliberately stays on the CPU. GRPO spends most of its time sampling rollouts, " +
		"and sampling is single-token decode.")
	d.p("So the GPU helps the policy-gradient forward and backward passes, which run over the full " +
		"sequence, and does nothing for the sampling that dominates the clock. Enable it, but do not " +
		"budget for a large speedup.")
	d.note("Measured locally at TF_THREADS=3: about 84 seconds per step on the hard task file, with " +
		"a range of 19 to 154 seconds depending on prompt length and how many rollouts hit the " +
		"96-token cap.")
}

