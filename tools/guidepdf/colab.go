func colabRun(d *doc) {
	d.h1("Running GRPO")

	d.h2("The command")
	d.code(
		"!./build/transformer-linux-x86_64-gpu grpo data/grpo_hard.txt \\",
		"    --model model/smollm/reason_e2.bin \\",
		"    --hf-tok model/smollm/tok.hf \\",
		"    --out model/smollm/grpo_hard.bin \\",
		"    --steps 100 --groups 4 --lr 1e-4 --verbose",
	)

	d.h2("The flags that matter")
	d.table([]string{"Flag", "Default", "What it does"}, []float64{34, 24, 116}, [][]string{
		{"--group", "8", "rollouts sampled per task; the group's own mean is the baseline that replaces a value network"},
		{"--groups", "1", "task groups accumulated into one optimizer step; this is the batch size, and 1 is a very noisy gradient"},
		{"--steps", "100", "optimizer steps"},
		{"--lr", "1e-5", "learning rate; RL wants far less than SFT, but see section 7"},
		{"--temp", "1.0", "sampling temperature - the exploration knob"},
		{"--lora-r", "8", "LoRA rank, base weights frozen"},
		{"--clip-eps", "0.2", "PPO-style ratio clip"},
		{"--kl", "0 (off)", "KL penalty toward the frozen base; costs one extra forward per rollout"},
		{"--seed", "-", "seeds BOTH task selection and token sampling"},
	})

	d.h2("Run it detached, and keep the log")
	d.p("A Colab cell that runs for an hour is a cell you cannot look at while it works. Redirect to " +
		"a log and tail it from another cell.")
	d.code(
		"import subprocess",
		"cmd = ['./build/transformer-linux-x86_64-gpu', 'grpo', 'data/grpo_hard.txt',",
		"       '--model', 'model/smollm/reason_e2.bin', '--hf-tok', 'model/smollm/tok.hf',",
		"       '--out', 'model/smollm/grpo_hard.bin', '--steps', '100',",
		"       '--groups', '4', '--lr', '1e-4', '--verbose']",
		"log = open('grpo_run.log', 'w')",
		"proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT)",
		"print('pid', proc.pid)",
		"",
		"# then, in a separate cell, as often as you like:",
		"!tail -n 20 grpo_run.log",
	)
	d.tip("Colab disconnects idle sessions. A browser tab left open on the notebook counts as idle " +
		"if nothing renders - tailing the log periodically also keeps the session alive.")
}

