func colabReading(d *doc) {
	d.h1("Reading the output")

	d.p("A GRPO step line looks like this:")
	d.code("  step    16/100  reward 0.9375  (running 0.6864, 4 flat groups skipped)  102.0s")

	d.h2("Flat groups are the number to watch")
	d.p("If every rollout in a group scores identically, every advantage is zero and the group is " +
		"skipped before any forward pass. GRPO learns from variance: where the model is uniformly " +
		"right or uniformly wrong there is no signal at all. A run reporting mostly flat groups is " +
		"not training, however healthy its reward looks.")
	d.p("This is not hypothetical. Running GRPO against the old SFT-derived task file produced five " +
		"flat groups out of five at a mean reward of exactly 1.0000 - a perfect score and a " +
		"completely useless run. The fix was harder tasks, not a hotter temperature.")

	d.h2("Reference numbers from 5 September 2026")
	d.table([]string{"Task file", "Temp", "Flat groups", "Mean reward"}, []float64{62, 22, 42, 48}, [][]string{
		{"data/grpo_tasks.txt (old, SFT-derived)", "1.0", "5 of 5", "1.0000"},
		{"data/grpo_tasks.txt", "1.5", "2 of 5", "0.9475"},
		{"data/grpo_hard.txt", "1.0", "2 of 10", "0.6712"},
		{"data/grpo_hard_eval.txt (held out)", "1.0", "7 of 20", "0.6144"},
	})
	d.note("A mean reward near 0.6 to 0.7 with most groups live is the target zone: real headroom " +
		"above, real spread below. A mean near 1.0 means the tasks are too easy to teach anything.")

	d.h2("The reward breakdown")
	d.p("With --verbose each group prints one scored sample. The three terms are independently " +
		"verifiable against something outside the model - the prompt text or the reference action - " +
		"and the breakdown tells you WHY reward moved:")
	d.table([]string{"Term", "Weight", "Meaning"}, []float64{28, 20, 126}, [][]string{
		{"format", "0.20", "exactly one well-formed, properly closed tool or done block, nothing trailing"},
		{"grounded", "0.30", "every argument occurs in the prompt as a whole token - catches hallucinated filenames"},
		{"match", "0.50", "the parsed action equals the reference; partial credit for right tool, wrong argument"},
	})
	d.p("Reward hacking shows up here first. A total that climbs while match stays flat means the " +
		"model has found a cheap way to satisfy format and grounding without doing the task.")
	d.warn("A total that climbs while match stays flat is not progress. Check the breakdown, not " +
		"just the total.")
}

