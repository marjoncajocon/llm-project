func colabTuning(d *doc) {
	d.h1("The hyperparameters, and what is still unknown")

	d.lead("As of 5 September 2026 the task data is solved and the optimization is not. This section " +
		"is the open question, stated honestly rather than dressed up as a recipe.")

	d.h2("What was measured")
	d.p("A 20-step run at the defaults - lr 1e-5, one group per step, LoRA rank 8 - changed the " +
		"weights but produced no behavioral change whatsoever. Two independent checks agree:")
	d.bullet("The first 10 steps of the 20-step run were bit-identical to a separate 10-step run: " +
		"same rewards, same running means, same flat-group counts, across 80 rollouts.")
	d.bullet("On 15 paired held-out steps - 120 rollouts, zero overlap with anything trained on - " +
		"the before and after checkpoints produced identical output at every step.")
	d.bullet("The checkpoints differ by SHA-256, so gradient is flowing and the plumbing is sound. " +
		"The updates are simply too small to change a single sampled token.")

	d.h2("The untested lever")
	d.p("Eight rollouts per update is a very noisy gradient, and 1e-5 is a small step for a LoRA " +
		"adapter on a 135M model. The obvious next experiment raises both:")
	d.code("--groups 4 --lr 1e-4      # 32 rollouts per update, 10x the step size")
	d.p("That is roughly four times the compute per step, which is precisely why it belongs on " +
		"Colab rather than on a desktop being used for anything else.")
	d.warn("This has NOT been run. It is the reasoned next experiment, not a validated recipe. " +
		"Treat the first result as information, not as a checkpoint to promote.")

	d.h2("How to tell quickly whether it is working")
	d.p("Do not wait for a hundred steps. Run twenty, then compare against the same twenty steps at " +
		"the old settings. Identical rewards step for step means the policy has not moved and the " +
		"settings are still too weak - that comparison costs twenty minutes and saves two hours.")
}

