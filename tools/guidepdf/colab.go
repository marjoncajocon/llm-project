// colab.go - generates build/colab_grpo.pdf, the guide to running this engine's
// GRPO reinforcement-learning loop on Google Colab.
//
//	cd tools/guidepdf && go run . -doc colab
//
// It shares doc.go's layout primitives with the main guide and overrides only the
// title page and the running footer, so the two documents stay visually identical
// without doc.go having to know that a second document exists.
package main

// newColabDoc builds a doc with the Colab guide's footer. newDoc installs the
// main guide's footer; SetFooterFunc replaces it wholesale, so this stays a
// pure addition rather than an edit to doc.go.
func newColabDoc(toc []entry, rec *[]entry) *doc {
	d := newDoc(toc, rec)
	pdf := d.pdf
	pdf.SetFooterFunc(func() {
		if pdf.PageNo() == 1 {
			return
		}
		pdf.SetY(-14)
		pdf.SetFont("Helvetica", "", 8)
		pdf.SetTextColor(120, 120, 120)
		pdf.CellFormat(bodyW/2, 6, "Running GRPO on Google Colab", "", 0, "L", false, 0, "")
		pdf.CellFormat(bodyW/2, 6, itoa(pdf.PageNo()), "", 0, "R", false, 0, "")
		pdf.SetTextColor(0, 0, 0)
	})
	return d
}

